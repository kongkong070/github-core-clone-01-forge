// reachability
// -------------------------------------------------------------------------------------------

export type ObjectLookup = (oid: string) => GitObject | undefined;

/**
 * Every object reachable from `tips`, walking commits (parents + tree),
 * trees (entries, recursively) and tags (their target). Throws when an
 * object the walk needs is missing.
 */
export function collectReachable(
  tips: Iterable<string>,
  lookup: ObjectLookup,
): Set<string> {
  const seen = new Set<string>();
  const stack = [...tips];
  while (stack.length > 0) {
    const oid = stack.pop() as string;
    if (seen.has(oid) || oid === ZERO_OID) continue;
    const object = lookup(oid);
    if (object === undefined) throw new Error(`missing object ${oid}`);
    seen.add(oid);
    if (object.type === 'commit') {
      const commit = parseCommit(object.data);
      stack.push(commit.tree);
      for (const parent of commit.parents) stack.push(parent);
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) stack.push(entry.oid);
    } else if (object.type === 'tag') {
      stack.push(parseTag(object.data).object);
    }
  }
  return seen;
}

/** True when `ancestor` is reachable from `tip` (or equal to it). */
export function isAncestor(ancestor: string, tip: string, lookup: ObjectLookup): boolean {
  if (ancestor === ZERO_OID) return true;
  if (ancestor === tip) return true;
  const seen = new Set<string>();
  const stack = [tip];
  while (stack.length > 0) {
    const oid = stack.pop() as string;
    if (seen.has(oid) || oid === ZERO_OID) continue;
    const object = lookup(oid);
    if (object === undefined) return false;
    seen.add(oid);
    if (object.type === 'commit') {
      for (const parent of parseCommit(object.data).parents) {
        if (parent === ancestor) return true;
        stack.push(parent);
      }
    } else if (object.type === 'tag') {
      stack.push(parseTag(object.data).object);
    }
  }
  return false;
}

/** The commit generation (distance in parents) of each commit reachable from a tip. */
export function commitGenerations(tips: Iterable<string>, lookup: ObjectLookup): Map<string, number> {
  const generations = new Map<string, number>();
  const queue: Array<{ oid: string; gen: number }> = [];
  for (const tip of tips) queue.push({ oid: tip, gen: 0 });
  while (queue.length > 0) {
    const current = queue.shift() as { oid: string; gen: number };
    if (current.oid === ZERO_OID) continue;
    const known = generations.get(current.oid);
    if (known !== undefined && known <= current.gen) continue;
    const object = lookup(current.oid);
    if (object === undefined || object.type !== 'commit') continue;
    generations.set(current.oid, current.gen);
    for (const parent of parseCommit(object.data).parents) {
      queue.push({ oid: parent, gen: current.gen + 1 });
    }
  }
  return generations;
}

